/// Абстрактный провайдер голосового Live-режима.
///
/// Скрывает конкретную реализацию realtime-соединения от интерфейса:
/// экран Live-режима работает только с этим контрактом. Конкретные
/// провайдеры (подключение к realtime-API выбранного сервиса) добавляются
/// отдельными классами и вводятся пользователем — адрес, ключ и модель
/// всегда берутся из пользовательских настроек, ничего не зашито в коде.
///
/// Аудио передаётся как сырые PCM-байты (16-бит, mono):
///  - [sendAudio] — отправка фрагмента с микрофона провайдеру;
///  - [audioStream] — поток входящих PCM-фрагментов для воспроизведения.
abstract class LiveProvider {
  /// Поток входящих аудио-фрагментов (PCM, List<int> байтов).
  /// Активен после успешного [connect].
  Stream<List<int>> get audioStream;

  /// Открывает сессию с провайдером по переданному API-ключу.
  /// Ключ вводится пользователем; метод не сохраняет и не логирует его.
  Future<void> connect(String apiKey);

  /// Отправляет фрагмент захваченного с микрофона аудио (PCM-байты).
  Future<void> sendAudio(List<int> pcmBytes);

  /// Закрывает сессию и освобождает ресурсы соединения.
  /// Безопасно вызывать повторно и до установления соединения.
  Future<void> disconnect();
}
